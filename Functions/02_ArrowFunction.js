//Arrow Function is the compact alternative to the traditional function expression with some difference

//Sum of two numbers using arrow function
const arrowSum=(a,b)=>{
    console.log(a+b);
}
arrowSum(2,4);

//Multiplication of two numbers using arrow function
const arrowMul=(a,b)=>{
    console.log(a*b);
}
arrowMul(2,2);